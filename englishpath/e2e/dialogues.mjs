import { chromium } from "playwright-core";
import { mkdirSync } from "node:fs";
const out = process.env.SHOTS ?? "e2e/screenshots";
mkdirSync(out, { recursive: true });
const BASE = process.env.BASE_URL ?? "http://localhost:4173/";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, colorScheme: "dark" });
const p = await ctx.newPage();
const errors = [];
p.on("console", (m) => { if (["error", "warning"].includes(m.type())) errors.push(`${m.type()}: ${m.text()}`); });
p.on("pageerror", (e) => errors.push("pageerror: " + e.message));
await p.goto(BASE);
await p.waitForTimeout(1500);
await p.getByRole("button", { name: /Get started/ }).click();
await p.getByRole("button", { name: /new to English/ }).click();
await p.waitForTimeout(600);
await p.getByRole("button", { name: "Dialogues" }).click();
await p.waitForTimeout(900);
await p.screenshot({ path: `${out}/30-dialogues.png` });
// Generate without key -> honest message
await p.getByRole("button", { name: /New dialogue for me/ }).click();
await p.waitForTimeout(700);
await p.screenshot({ path: `${out}/31-dialogues-nokey.png` });
await p.getByRole("button", { name: /Buying Fruit/ }).click();
await p.waitForTimeout(600);
await p.screenshot({ path: `${out}/32-sheet.png` });
await p.getByRole("button", { name: /Listen & learn/ }).click();
await p.waitForTimeout(600);
for (let i = 0; i < 7; i++) { await p.getByRole("button", { name: "Next line" }).click(); await p.waitForTimeout(250); }
await p.waitForTimeout(600);
await p.screenshot({ path: `${out}/33-listen.png` });
await p.getByRole("button", { name: /Done/ }).click();
await p.waitForTimeout(2200);
await p.screenshot({ path: `${out}/33b-achievement.png` });
await p.getByRole("button", { name: "Keep going" }).click();
await p.waitForTimeout(600);
await p.getByRole("button", { name: /Buying Fruit/ }).click();
await p.waitForTimeout(400);
await p.getByRole("button", { name: /Role-play/ }).click();
await p.waitForTimeout(800);
const send = async (t) => { await p.getByRole("textbox", { name: "Your reply" }).fill(t); await p.getByRole("button", { name: "Send" }).click(); await p.waitForTimeout(500); };
await send("Yes please. How much is the apples?");
await send("I want a car");
await send("I like one kilo, please");
await p.getByRole("button", { name: "Show a hint" }).click();
await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/34-roleplay.png` });
await send("No, thanks. Here's two dollars.");
await send("You too. Bye!");
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/35-roleplay-done.png` });
// Back button from dialogue returns to list; from tab root goes to Learn
await p.getByRole("button", { name: /Back to dialogues/ }).click();
await p.waitForTimeout(500);
await p.keyboard.press("Escape");
await p.waitForTimeout(600);
const h1 = await p.locator("h1").first().innerText();
console.log("after back on Dialogues root ->", h1);
const realErrors = errors.filter((e) => !e.includes("GL Driver"));
console.log(realErrors.join("\n") || "no console errors");
if (!h1.includes("path") || realErrors.length) { console.error("E2E FAILED"); process.exitCode = 1; } else console.log("E2E PASSED: dialogues, role-play, achievement, back to Learn");
await b.close();
